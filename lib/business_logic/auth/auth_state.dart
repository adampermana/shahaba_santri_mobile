part of 'auth_bloc.dart';

@freezed
abstract class AuthState with _$AuthState {
  const factory AuthState({
    required String? message,
    required String? messageVerifyOtp,
    required bool loading,
    required bool loadingUser,
    required bool loadingGuest,
    required bool loadingAi,
    required bool loadingVerifyEmail,
    required bool loadingResendOtp,
    required bool loadingRestoreAccount,
    required bool successLoginUser,
    required bool successLoginGuest,
    required bool successLoginAi,
    required bool successRegister,
    required bool successVerifyEmail,
    required bool successResendOtp,
    required bool successRestoreAccount,
    required bool isEmailUnverified,
    required int cooldownOtp,
    required String? pendingEmail,
    required LoginResponse? loginResponse,
    required LoginResponAI? loginAiResponse,
    required RegisterResponse? registerResponse,
    required VerifyOtpResponse? verifyEmailResponse,
    required ResendOtpResponse? resendOtpResponse,
    required AuthDataHive? authDataHive,
    required AuthDataKatanaraHive? authAiDataHive,
    required Alert? alert,
  }) = _Initial;

  factory AuthState.initial() => const AuthState(
    message: null,
    messageVerifyOtp: null,
    loading: false,
    loadingUser: false,
    loadingGuest: false,
    loadingAi: false,
    loadingVerifyEmail: false,
    loadingResendOtp: false,
    loadingRestoreAccount: false,
    successLoginUser: false,
    successLoginGuest: false,
    successLoginAi: false,
    successRegister: false,
    successVerifyEmail: false,
    successResendOtp: false,
    successRestoreAccount: false,
    isEmailUnverified: false,
    cooldownOtp: 60,
    pendingEmail: null,
    loginResponse: null,
    loginAiResponse: null,
    registerResponse: null,
    verifyEmailResponse: null,
    resendOtpResponse: null,
    authDataHive: null,
    authAiDataHive: null,
    alert: null,
  );
}
